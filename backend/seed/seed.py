"""Generate the SAMVAAD demo evidence dataset. Every record is data_status="demo".

Usage (from backend/):  python -m seed.seed            # replace evidence tables only
                        python -m seed.seed --all      # also wipe sessions, messages, cases, events
"""
import argparse
import random

from sqlalchemy import delete
from sqlalchemy.orm import Session

from app import models as m
from app.config import DISTRICTS, STATE
from app.db import SessionLocal
from app.schema_setup import upgrade_to_head

from .reference_data import (
    DISTRICT_FACTORS, FEES, LADDERS, MISSING_DISTRICT, MISSING_STATE, MISSING_YEAR, NATIONAL_ROWS,
    PROVIDER_GAPS, PROVIDER_TEMPLATES, TRADES, YEARS, COST_TEXT,
)

DEMO_SOURCE_TITLE = "SAMVAAD simulated demo dataset"
EVIDENCE_TABLES = [m.Outcome, m.CostSupport, m.ProgressionStep, m.Provider, m.Trade, m.Source]
ENGAGEMENT_TABLES = [m.CallbackRequest, m.Escalation, m.GuardrailLog, m.EvidenceGap, m.Event,
                     m.AlignmentResponse, m.Message, m.SessionRow]


def round_to(x: float, step: int = 500) -> int:
    return int(round(x / step) * step)


def clear(db: Session, include_engagement: bool) -> None:
    # evidence_gaps reference trades only by slug, so they survive an evidence-only reseed.
    tables = (ENGAGEMENT_TABLES if include_engagement else []) + EVIDENCE_TABLES
    for model in tables:
        db.execute(delete(model))
    db.commit()


def outcome_row(rng: random.Random, trade: m.Trade, base: dict, src: m.Source, geo: str,
                district: str | None, year: int, earn_factor: float, place_offset: float) -> m.Outcome:
    growth = 1 + 0.04 * (year - 2023)
    jitter = rng.uniform(0.96, 1.04)
    f = earn_factor * growth * jitter
    median = round_to(base["median"] * f)
    lo = round_to(base["min"] * f)
    hi = round_to(base["max"] * f)
    sample = {"district": rng.randint(60, 240), "state": rng.randint(900, 2400),
              "national": rng.randint(9000, 30000)}[geo]
    rate = max(40, min(92, base["placement"] + place_offset + rng.uniform(-3, 3) + (year - 2023)))
    placed = int(round(sample * rate / 100))
    return m.Outcome(
        trade_id=trade.id, provider_id=None, geo_level=geo, district=district, year=year,
        reporting_period=YEARS[year], placement_numerator=placed, placement_denominator=sample,
        placement_rate=float(round(100 * placed / sample)), earnings_min=lo, earnings_max=hi,
        earnings_median=median, earnings_basis="monthly", currency="INR", sample_size=sample,
        source_id=src.id, data_status="demo", verified_on=None,
    )


def seed(db: Session, rng_seed: int = 42) -> dict:
    rng = random.Random(rng_seed)
    src = m.Source(
        title=DEMO_SOURCE_TITLE, url=None, publisher="SAMVAAD team",
        reporting_period="FY 2023-24 to FY 2025-26", verified_on=None,
        notes="Generated by backend/seed/seed.py. Plausible but NOT real. Replace with organiser data.",
    )
    db.add(src)
    db.flush()

    trades: dict[str, m.Trade] = {}
    for t in TRADES:
        row = m.Trade(**{k: v for k, v in t.items() if k != "base"})
        db.add(row)
        trades[t["slug"]] = row
    db.flush()

    counts = {"outcomes": 0, "steps": 0, "providers": 0, "costs": 0}
    for t in TRADES:
        trade, base = trades[t["slug"]], t["base"]
        for year in YEARS:
            for d in DISTRICTS:
                if (t["slug"], d) in MISSING_DISTRICT or (t["slug"], d, year) in MISSING_YEAR:
                    continue
                fac = DISTRICT_FACTORS[d]
                db.add(outcome_row(rng, trade, base, src, "district", d, year, fac["earn"], fac["place"]))
                counts["outcomes"] += 1
            if t["slug"] not in MISSING_STATE:
                db.add(outcome_row(rng, trade, base, src, "state", None, year, 1.03, 0))
                counts["outcomes"] += 1
            if t["slug"] in NATIONAL_ROWS:
                db.add(outcome_row(rng, trade, base, src, "national", None, year, 0.95, -3))
                counts["outcomes"] += 1

        for step in LADDERS[t["slug"]]:
            db.add(m.ProgressionStep(trade_id=trade.id, source_id=src.id, **step))
            counts["steps"] += 1

        if t["slug"] in FEES:
            lo, hi = FEES[t["slug"]]
            db.add(m.CostSupport(
                trade_id=trade.id, district=None, fee_min=lo, fee_max=hi, support_type="none",
                description=COST_TEXT["fee"],
                source_id=src.id, data_status="demo", income_brackets=[],
            ))
            db.add(m.CostSupport(
                trade_id=trade.id, district=None, fee_min=0, fee_max=0, support_type="scheme",
                description=COST_TEXT["scheme"],
                source_id=src.id, data_status="demo", income_brackets=["<1.5L", "1.5-3L"],
            ))
            db.add(m.CostSupport(
                trade_id=trade.id, district=None, fee_min=None, fee_max=None, support_type="stipend",
                description=COST_TEXT["stipend"],
                source_id=src.id, data_status="demo", income_brackets=[],
            ))
            counts["costs"] += 3
            # Bengaluru has its own (higher) private fee band.
            db.add(m.CostSupport(
                trade_id=trade.id, district="Bengaluru Urban", fee_min=lo, fee_max=round_to(hi * 1.3),
                support_type="none",
                description=COST_TEXT["blr_fee"],
                source_id=src.id, data_status="demo", income_brackets=[],
            ))
            counts["costs"] += 1

    for d in DISTRICTS:
        for name, ptype, offered in PROVIDER_TEMPLATES:
            offered_here = [s for s in offered if (s, d) not in PROVIDER_GAPS]
            db.add(m.Provider(name=name.format(d=d), district=d, state=STATE, provider_type=ptype,
                              accreditation=None, data_status="demo", trades=offered_here))
            counts["providers"] += 1

    db.commit()
    return counts


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--all", action="store_true", help="also wipe engagement tables (sessions, messages, ...)")
    args = ap.parse_args()
    upgrade_to_head()
    with SessionLocal() as db:
        clear(db, include_engagement=args.all)
        counts = seed(db)
    print("Seeded demo evidence (all data_status=demo):", counts)


if __name__ == "__main__":
    main()
